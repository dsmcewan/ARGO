"""Generate only TypeScript structure from the frozen schema; Ajv enforces runtime constraints."""
import json, pathlib, sys
root=pathlib.Path(__file__).resolve().parents[1]
schema=json.loads((root/'SYSTEMS/argo-v1.schema.json').read_text())
def emit(s):
 if '$ref' in s: return s['$ref'].split('/')[-1]
 if 'const' in s: return json.dumps(s['const'])
 if 'enum' in s: return '('+' | '.join(map(json.dumps,s['enum']))+')'
 for key in ['oneOf','anyOf']:
  if key in s: return '('+' | '.join(map(emit,s[key]))+')'
 t=s.get('type')
 if t in ['integer','number']: return 'number'
 if t in ['string','boolean','null']: return t
 if t=='array': return 'Array<'+emit(s['items'])+'>'
 if t=='object':
  if isinstance(s.get('additionalProperties'),dict): return 'Record<string, '+emit(s['additionalProperties'])+'>'
  return '{ '+ '; '.join(json.dumps(k)+('' if k in s.get('required',[]) else '?')+': '+emit(v) for k,v in s.get('properties',{}).items())+' }'
 raise ValueError(s)
text='// Generated by scripts/generate-contract-types.py. Runtime validation is mandatory.\n'
text+='\n'.join('export type '+k+' = '+emit(v)+';' for k,v in schema['$defs'].items())+'\n'
text+='export interface ContractMap { '+'; '.join(k+': '+k for k in schema['$defs'])+' }\n'
p=root/'packages/contracts/src/generated.ts'
if '--check' in sys.argv:
 if not p.exists() or p.read_text()!=text: raise SystemExit('Generated contract types differ from frozen schema')
else: p.write_text(text)
