#!/usr/bin/env python3
"""Generate additive projection TypeScript structures from the real schema.

Only structural types are emitted. JSON Schema and the runtime semantic guards
remain authoritative for bounds, ordering, cross-field equality and authority.
No dependencies, downloads, schema expansion or changes to frozen v1 types.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

SCHEMA_PATH = Path('SYSTEMS/proposals/headless-v2/projection-v2.schema.json')
OUTPUT_PATH = Path('packages/contracts/src/projection-generated.ts')
V1_PATH = Path('SYSTEMS/argo-v1.schema.json')


def generate(schema: dict, v1_schema: dict, source_bytes: bytes) -> str:
    definitions = schema.get('$defs')
    if not isinstance(definitions, dict) or not definitions:
        raise ValueError('Projection schema needs nonempty $defs')
    for name in definitions:
        if not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]*', name):
            raise ValueError(f'Unsupported TypeScript definition name: {name!r}')
    v1_id = v1_schema.get('$id')
    if not isinstance(v1_id, str) or 'Scope' not in v1_schema.get('$defs', {}):
        raise ValueError('Frozen v1 schema lacks its ID or Scope definition')
    scope_ref = v1_id + '#/$defs/Scope'
    own_id = schema.get('$id')

    def literal(value):
        return json.dumps(value, ensure_ascii=False, separators=(',', ':'))

    def resolve_reference(reference):
        if reference == scope_ref:
            return 'Scope'
        local = reference
        if isinstance(own_id, str) and local.startswith(own_id + '#'):
            local = local[len(own_id):]
        if not local.startswith('#/$defs/'):
            raise ValueError(f'Unsupported schema reference: {reference!r}')
        encoded = local[len('#/$defs/'):]
        if '/' in encoded or re.search(r'~(?![01])', encoded):
            raise ValueError(f'Unsupported schema reference: {reference!r}')
        name = encoded.replace('~1', '/').replace('~0', '~')
        if name not in definitions:
            raise ValueError(f'Unknown local schema reference: {reference!r}')
        return 'Projection' + name

    def emit(node):
        if not isinstance(node, dict):
            raise ValueError('Only explicit schema objects can generate types')
        if '$ref' in node:
            return resolve_reference(node['$ref'])
        if 'const' in node:
            return literal(node['const'])
        if 'enum' in node:
            return '(' + ' | '.join(literal(value) for value in node['enum']) + ')'
        for combinator in ('oneOf', 'anyOf'):
            if combinator in node:
                return '(' + ' | '.join(emit(item) for item in node[combinator]) + ')'
        kind = node.get('type')
        if isinstance(kind, list):
            return '(' + ' | '.join(emit(dict(node, type=item)) for item in kind) + ')'
        if kind in ('integer', 'number'):
            return 'number'
        if kind in ('string', 'boolean', 'null'):
            return kind
        if kind == 'array':
            if 'items' not in node or 'prefixItems' in node:
                raise ValueError('Only homogeneous bounded array structures are supported')
            return 'Array<' + emit(node['items']) + '>'
        if kind == 'object':
            properties = node.get('properties', {})
            required = set(node.get('required', []))
            patterns = node.get('patternProperties', {})
            additional = node.get('additionalProperties', False)
            if patterns or isinstance(additional, dict):
                if properties or (patterns and isinstance(additional, dict)) or len(patterns) > 1:
                    raise ValueError('Mixed fixed/dynamic object structures need explicit generator support')
                child = next(iter(patterns.values())) if patterns else additional
                # An index signature permits direct recursive JsonValue aliases;
                # Record<string, JsonValue> needlessly introduces circular-alias issues.
                return '{ [key: string]: ' + emit(child) + ' }'
            if additional is not False:
                raise ValueError('Unbounded additional properties need an explicit structural type')
            if not required.issubset(properties):
                raise ValueError('Required object fields are absent from properties')
            return '{ ' + '; '.join(
                literal(name) + ('' if name in required else '?') + ': ' + emit(child)
                for name, child in properties.items()
            ) + ' }'
        if 'allOf' in node:
            return '(' + ' & '.join(emit(item) for item in node['allOf']) + ')'
        raise ValueError(f'Unsupported structural schema: {node!r}')

    lines = [
        '// Generated by scripts/generate-projection-types.py. Runtime validation is mandatory.',
        '// Schema SHA-256: ' + hashlib.sha256(source_bytes).hexdigest(),
        "import type {Scope} from './generated.ts';",
    ]
    lines.extend('export type Projection' + name + ' = ' + emit(value) + ';'
                 for name, value in definitions.items())
    lines.append('export interface ProjectionContractMap { ' + '; '.join(
        literal(name) + ': Projection' + name for name in definitions
    ) + ' }')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Refuse missing/stale output without modifying files')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1],
                        help='Repository/staging root (defaults to this installed script repository)')
    options = parser.parse_args()
    try:
        source = (options.root / SCHEMA_PATH).read_bytes()
        schema = json.loads(source)
        v1_schema = json.loads((options.root / V1_PATH).read_text(encoding='utf-8'))
        rendered = generate(schema, v1_schema, source)
        output = options.root / OUTPUT_PATH
        if options.check:
            if not output.is_file() or output.read_text(encoding='utf-8') != rendered:
                print('Generated projection types differ from the projection schema', file=sys.stderr)
                return 1
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(rendered, encoding='utf-8', newline='\n')
    except (OSError, ValueError, TypeError, KeyError) as error:
        print('Projection type generation refused: ' + str(error), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
