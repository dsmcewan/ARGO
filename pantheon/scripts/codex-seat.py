#!/usr/bin/env python3
"""One Pantheon role turn run as a Codex thread, via the Codex Python SDK.

WHY THIS EXISTS AS A SCRIPT. Pantheon is Node, and its rule is that no pipeline module imports a
vendor SDK -- clients arrive through makeClientFor(vendor). The Codex SDK is Python, so it cannot
be injected that way at all. scripts/agy-seat.py already solved the same problem for Antigravity by
shelling out to a venv python, and this follows that shape deliberately rather than inventing a
second one.

WHY CODEX CAN BE SEATED AT ALL NOW. Codex was previously reachable only as a CLI, and a CLI needs a
controlling terminal -- which is exactly what this harness does not have (`tty` reports "not a
tty"), and why earlier seat launchers died with "os error 6". The Python SDK drives a bundled
binary over JSON-RPC with explicit cwd/env, so no terminal is involved.

THE SEAT SPEC. Generated by src/agents/render.mjs (`codex` format) from the canonical store. Its
top-level keys are EXACTLY thread_start()'s keyword arguments, so they splat without a translation
layer that could drift from the SDK. Everything Pantheon-specific lives under "pantheon" and is
never passed to the SDK.

    .venv-codex/bin/python scripts/codex-seat.py \\
        --spec .pantheon/codex-seats/pantheon-reviewer-openai-gpt-6-astra.json \\
        --workspace /path/to/worktree \\
        --prompt-file /path/to/prompt.txt

Prints one JSON object on stdout. Progress goes to stderr, so stdout stays parseable.
"""
import argparse
import json
import os
import sys
import time
from pathlib import Path

T0 = time.time()


def progress(event: str, **kw) -> None:
    """Progress on stderr only. A stray print() to stdout corrupts the one JSON result."""
    rec = {"elapsed_s": round(time.time() - T0, 2), "event": event, **kw}
    print(json.dumps(rec, ensure_ascii=False), file=sys.stderr, flush=True)


# thread_start() accepts these; anything else in a spec is refused rather than silently dropped,
# because a typo'd key that vanishes is a seat running without the setting its author intended.
THREAD_START_KEYS = {
    "developer_instructions", "sandbox", "approval_mode", "model", "model_provider",
    "base_instructions", "config", "cwd", "ephemeral", "personality", "service_tier",
}


def load_spec(path: Path) -> tuple[dict, dict]:
    """Returns (thread_start kwargs, pantheon metadata)."""
    spec = json.loads(path.read_text(encoding="utf-8"))
    pantheon = spec.pop("pantheon", {})
    unknown = set(spec) - THREAD_START_KEYS
    if unknown:
        raise SystemExit(
            f"{path}: key(s) {sorted(unknown)} are not thread_start() parameters. "
            f"Refusing rather than dropping them -- a silently ignored setting is a seat that "
            f"does not do what its spec says.")
    if not spec.get("developer_instructions"):
        raise SystemExit(f"{path}: developer_instructions is empty; that IS the agent definition.")
    return spec, pantheon


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--spec", required=True, type=Path, help="seat spec JSON from the agent store")
    ap.add_argument("--workspace", required=True, type=Path, help="cwd for the thread")
    ap.add_argument("--prompt-file", required=True, type=Path, help="the turn's input")
    ap.add_argument("--effort", default=None, help="reasoning effort for the turn")
    ap.add_argument("--dry-run", action="store_true",
                    help="resolve and validate everything, then print the call WITHOUT making it")
    a = ap.parse_args()

    kwargs, pantheon = load_spec(a.spec)
    if not a.workspace.is_dir():
        raise SystemExit(f"--workspace {a.workspace} is not a directory")
    kwargs["cwd"] = str(a.workspace.resolve())
    prompt = a.prompt_file.read_text(encoding="utf-8")

    progress("seat.resolved", role=pantheon.get("role"), seat=pantheon.get("id"),
             sandbox=kwargs.get("sandbox"), approval_mode=kwargs.get("approval_mode"))

    # Imported here, not at module scope, so --dry-run and --help work without the SDK installed
    # and so an import failure is reported as this seat's error rather than a bare traceback.
    try:
        from openai_codex import Codex, CodexConfig, Sandbox, ApprovalMode
    except ImportError as e:
        raise SystemExit(f"openai_codex is not importable ({e}). Install it into a venv: "
                         f"python3 -m venv .venv-codex && .venv-codex/bin/pip install openai-codex")

    # The SDK takes enums, not the bare strings the spec carries. Converting here (rather than
    # emitting enum names in the JSON) keeps the spec readable and runtime-independent.
    if "sandbox" in kwargs:
        kwargs["sandbox"] = Sandbox(kwargs["sandbox"])
    if "approval_mode" in kwargs:
        kwargs["approval_mode"] = ApprovalMode(kwargs["approval_mode"])

    if a.dry_run:
        # Proves the spec resolves to a real call without spending a turn: every key is a known
        # parameter and every enum value is accepted by the SDK's own enum.
        print(json.dumps({
            "ok": True, "dry_run": True, "seat": pantheon.get("id"),
            "thread_start_kwargs": {k: getattr(v, "value", v) for k, v in kwargs.items()
                                    if k != "developer_instructions"},
            "developer_instructions_chars": len(kwargs["developer_instructions"]),
            "prompt_chars": len(prompt),
        }, ensure_ascii=False))
        return 0

    codex = Codex(CodexConfig(cwd=str(a.workspace.resolve()), env=dict(os.environ)))
    progress("thread.start")
    thread = codex.thread_start(**kwargs)

    run_kwargs = {}
    if a.effort:
        run_kwargs["effort"] = a.effort
    progress("turn.run")
    result = thread.run(prompt, **run_kwargs)

    text = getattr(result, "final_response", None) or getattr(result, "text", None) or str(result)
    progress("turn.done", chars=len(text))
    print(json.dumps({
        "ok": True, "seat": pantheon.get("id"), "role": pantheon.get("role"),
        "thread_id": getattr(thread, "id", None), "text": text,
    }, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
