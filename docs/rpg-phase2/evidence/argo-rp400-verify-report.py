#!/usr/bin/env python3
"""Independent report-only ARGO balance verifier. Never imports the kernel or runs trials.

Input: a retained train/holdout report, plus the frozen decision (and training report
for holdout). Reconstructs complete integer outcome rows from compact columns,
then independently computes aggregates, hashes, intervals and selection. It does
not prove the outcome rows were generated by the claimed kernel: no transition
transcripts are in these reports, so state/transition hashes cannot be recomputed.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import re
from pathlib import Path
from statistics import NormalDist

PROTOCOL = 'mortal-balance/1.0.0'
RESOURCES = ['rations', 'water', 'oil', 'obols', 'ammo']
CASES = ['light_exact','light_short','search_forage','needs_prepared','needs_short','rest_prepared','rest_short','clock_isolation']
COMBAT_COLUMNS = 'trial initial_die max_hp hp standing unconscious dead escaped retreat_admitted won censored started_rounds charged_rounds world_seconds active_seconds actions sequence rng_counter player_attacks location resources state_hash transition_digest replay_digest replay_verified'.split()
RESOURCE_COLUMNS = 'trial objective_completed hp standing unconscious dead location resources initial_resources world_seconds active_seconds fed_until next_rest_at discoveries forage_remaining stocks rests refusals refusal_codes actions sequence rng_counter state_hash transition_digest replay_digest replay_verified'.split()
Z95 = NormalDist().inv_cdf(.975)
TARGET_Z = NormalDist().inv_cdf(1 - .05/4)
PAIRED_TARGET_Z = NormalDist().inv_cdf(1 - .05/8)
METHOD = 'union-bounded Wilson score marginals for p(improved)-p(worsened); nominal score coverage, not an exact finite-sample guarantee'
SELECTION_RULE = 'Retain classic if all preregistered adjusted target intervals match; otherwise floor4 only if its intervals match; otherwise no-target-match. Any censorship prevents recommendation.'
ANALYSIS_NOTE = 'Floating means and confidence intervals are analysis only. Wilson binomial and union-bounded paired score intervals assume these fixed pseudorandom seeds represent the declared encounter distribution; they do not prove fun, universal balance, physical dice fairness or deployment safety.'
CHECKS = 0

def require(condition, message):
    global CHECKS
    CHECKS += 1
    if not condition:
        raise ValueError(message)

def compare(actual, expected, path='$'):
    if isinstance(expected, dict):
        require(isinstance(actual, dict), f'{path}: not object')
        require(actual.keys() == expected.keys(), f'{path}: fields differ {actual.keys() ^ expected.keys()}')
        for key in expected:
            compare(actual[key], expected[key], f'{path}.{key}')
    elif isinstance(expected, list):
        require(isinstance(actual, list) and len(actual) == len(expected), f'{path}: length/type differs')
        for index, (a, e) in enumerate(zip(actual, expected)):
            compare(a, e, f'{path}[{index}]')
    elif isinstance(expected, float):
        require(type(actual) in (int, float) and math.isfinite(actual) and math.isclose(actual, expected, rel_tol=1e-12, abs_tol=1e-12), f'{path}: {actual!r} != {expected!r}')
    else:
        # JavaScript serializes integer-valued analysis floats as integers.
        require(type(actual) is type(expected) and actual == expected, f'{path}: {actual!r} != {expected!r}')

def integer_dto(value, path='$'):
    if isinstance(value, dict):
        for key, child in value.items():
            require(isinstance(key, str), f'{path}: nonstring key')
            integer_dto(child, f'{path}.{key}')
    elif isinstance(value, list):
        for index, child in enumerate(value):
            integer_dto(child, f'{path}[{index}]')
    elif type(value) is int:
        require(abs(value) <= 2**53 - 1, f'{path}: unsafe integer')
    else:
        require(value is None or type(value) in (str, bool), f'{path}: not an integer DTO')

def canonical_bytes(value):
    integer_dto(value)
    return json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':'), allow_nan=False).encode('utf8')

def digest(value):
    return hashlib.sha256(canonical_bytes(value)).hexdigest()

def duplicate_free(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate JSON key: {key}')
        result[key] = value
    return result

def load(path):
    raw = Path(path).read_bytes()
    value = json.loads(raw, object_pairs_hook=duplicate_free,
                       parse_constant=lambda x: (_ for _ in ()).throw(ValueError(f'Nonfinite JSON value {x}')))
    return value, hashlib.sha256(raw).hexdigest()

def sha(value, path):
    require(type(value) is str and re.fullmatch('[0-9a-f]{64}', value), f'{path}: invalid SHA-256')

def uint(value, path):
    require(type(value) is int and 0 <= value <= 2**53-1, f'{path}: invalid nonnegative safe integer')

def wilson(successes, n, z=Z95):
    require(type(n) is int and type(successes) is int and 0 <= successes <= n, 'Invalid binomial count')
    if n == 0:
        return None
    # Independent algebraic form of the Wilson score interval.
    denominator = n + z*z
    center = (successes + z*z/2) / denominator
    radius = z * math.sqrt(successes*(n-successes)/n + z*z/4) / denominator
    return {'low': 0 if successes == 0 else max(0, center-radius),
            'high': 1 if successes == n else min(1, center+radius)}

def paired(a, b, purpose='descriptive'):
    require(len(a) == len(b), 'Unpaired arrays')
    counts = dict(improved=0, worsened=0, both=0, neither=0)
    for left, right in zip(a, b):
        counts['both' if left and right else 'improved' if left else 'worsened' if right else 'neither'] += 1
    n = len(a)
    z = PAIRED_TARGET_Z if purpose == 'target' else TARGET_Z
    imp, wor = wilson(counts['improved'], n, z), wilson(counts['worsened'], n, z)
    return {'count':n, 'counts':counts,
            'mean':(counts['improved']-counts['worsened'])/n if n else 0,
            'interval':{'low':max(-1, imp['low']-wor['high']), 'high':min(1, imp['high']-wor['low'])} if n else {'low':-1,'high':1},
            'marginal_intervals':{'improved':imp,'worsened':wor},
            'marginal_one_sided_alpha':.00625 if purpose == 'target' else .0125,
            'method':METHOD}

def comparison(hp, fight, escape):
    require([r['trial'] for r in fight] == [r['trial'] for r in escape], 'Mismatched paired trial IDs')
    censored = sum(a['censored'] or b['censored'] for a,b in zip(fight, escape))
    if censored:
        return {'hp':hp, 'censored_pairs':censored, 'paired95':None,
                'target':{'status':'inconclusive','reason':'censored-comparison','censored_pairs':censored,'danger':None,'escape':None,'delta':None}}
    a, b = [r['standing'] for r in escape], [r['standing'] for r in fight]
    danger = wilson(sum(r['unconscious'] or r['dead'] for r in fight), len(fight), TARGET_Z)
    escaped = wilson(sum(r['escaped'] for r in escape), len(escape), TARGET_Z)
    delta = paired(a,b,'target')['interval']
    if len(fight) < 500:
        status, reason = 'inconclusive', 'insufficient-study'
    elif danger['low'] >= .20 and danger['high'] <= .60 and escaped['low'] >= .85 and delta['low'] >= .15:
        status, reason = 'match', 'target-bounds-match'
    elif danger['high'] < .20 or danger['low'] > .60 or escaped['high'] < .85 or delta['high'] < .15:
        status, reason = 'miss', 'target-bounds-miss'
    else:
        status, reason = 'inconclusive', 'target-boundary-overlap'
    return {'hp':hp, 'censored_pairs':0, 'paired95':paired(a,b),
            'target':{'status':status,'reason':reason,'censored_pairs':0,'danger':danger,'escape':escaped,'delta':delta}}

def arms():
    result = []
    for hp in ('classic','floor4'):
        for armor in (11,12,14):
            for policy in ('fight','immediate','threshold'):
                result.append(dict(id=f'solo_{hp}_a{armor}_{policy}',hp=hp,armor=armor,policy=policy,enemies=1))
    for policy in ('fight','immediate','threshold'):
        result.append(dict(id=f'outnumbered_classic_a11_{policy}',hp='classic',armor=11,policy=policy,enemies=2))
    return result

def reconstruct(summary, columns, enclosing, identity, n):
    compare(summary['seed_rows']['columns'], columns, identity+'.columns')
    require(len(summary['seed_rows']['rows']) == n, identity+': row count')
    result = []
    for index, values in enumerate(summary['seed_rows']['rows']):
        require(type(values) is list and len(values) == len(columns), identity+': row width')
        row = dict(zip(columns, values))
        row[enclosing] = identity
        integer_dto(row)
        require(row['trial'] == index, identity+': trial ordering')
        for field in ('standing','unconscious','dead','replay_verified'):
            require(type(row[field]) is bool, identity+'.'+field+': not bool')
        require(row['standing'] == (row['hp'] > 0) and row['unconscious'] == (row['hp'] == 0) and row['dead'] == (row['hp'] < 0), identity+': health classification')
        require(type(row['hp']) is int and -1000000 <= row['hp'] <= 1000000, identity+': HP type/bound')
        for field in ('state_hash','transition_digest','replay_digest'):
            sha(row[field], identity+'.'+field)
        require(row['transition_digest'] == row['replay_digest'] and row['replay_verified'] is True, identity+': replay assertion differs')
        require(set(row['resources']) == set(RESOURCES), identity+': resources shape')
        for field in RESOURCES:
            uint(row['resources'][field], identity+'.resources.'+field)
        for field in ('world_seconds','active_seconds','actions','sequence','rng_counter'):
            uint(row[field], identity+'.'+field)
        result.append(row)
    return result

def compact(rows, columns):
    return {'columns':columns, 'rows':[[row[key] for key in columns] for row in rows]}

def totals(rows, fields):
    return {field:sum(row[field] for row in rows) for field in fields}

def row_digests(rows):
    return {'replay_verified_trials':len(rows),
            'replay_digest':digest([{'trial':row['trial'],'digest':row['replay_digest']} for row in rows]),
            'integer_results_digest':digest(rows)}

def combat_summary(arm, rows, phase):
    n = len(rows)
    for row in rows:
        identity = arm['id']+':'+str(row['trial'])
        raw_hp = 1+hashlib.sha256(f"{PROTOCOL}|initial-hp|{phase}|{row['trial']}".encode()).digest()[0] % 8
        require(row['initial_die'] == raw_hp, identity+': initial HP draw')
        require(row['max_hp'] == (raw_hp if arm['hp']=='classic' else max(4,raw_hp)), identity+': max HP')
        require(row['hp'] <= row['max_hp'], identity+': HP exceeds maximum')
        for field in ('escaped','retreat_admitted','won','censored'):
            require(type(row[field]) is bool, identity+': nonboolean '+field)
        for field in ('started_rounds','charged_rounds','player_attacks'):
            uint(row[field], identity+'.'+field)
        require(row['escaped'] == (row['retreat_admitted'] and row['standing']), identity+': escape classification')
        require(not row['won'] or (not row['censored'] and not row['retreat_admitted'] and row['standing']), identity+': victory necessary conditions')
        require(not row['censored'] or (row['standing'] and not row['escaped'] and not row['won']), identity+': capped outcome')
        require(row['actions'] == row['sequence'] and 1 <= row['actions'] <= 500, identity+': sequence/actions')
        require(row['charged_rounds'] <= 100 and row['started_rounds'] == row['charged_rounds']+int(row['censored']), identity+': round accounting')
        require(row['world_seconds'] == 6*row['charged_rounds'] and row['active_seconds'] == row['world_seconds'], identity+': duration')
        attacks = row['actions']-1-int(row['retreat_admitted'])
        require(0 <= row['player_attacks'] <= attacks, identity+': attacks')
        require(1+attacks <= row['rng_counter'] <= 1+2*attacks, identity+': RNG count bounds')
        require(row['location'] == 'arena', identity+': combat location')
    endpoints = {field:sum(row[field] for row in rows) for field in ('unconscious','dead','escaped','won','censored')}
    endpoints.update(standing_at_stop=sum(row['standing'] for row in rows),terminal_standing=sum(row['standing'] and not row['censored'] for row in rows))
    sums = totals(rows,['started_rounds','charged_rounds','actions','world_seconds','active_seconds','rng_counter'])
    strata = []
    for die in range(1,9):
        group = [row for row in rows if row['initial_die'] == die]
        stratum = dict(die=die,count=len(group),standing_at_stop=sum(row['standing'] for row in group),terminal_standing=sum(row['standing'] and not row['censored'] for row in group))
        stratum.update({field:sum(row[field] for row in group) for field in ('escaped','unconscious','dead','censored')})
        strata.append(stratum)
    return dict(arm=arm,count=n,endpoints=endpoints,totals=sums,
                means={field:sums[field]/n for field in ('started_rounds','charged_rounds')},
                intervals95=None if endpoints['censored'] else dict(incapacitated=wilson(endpoints['unconscious']+endpoints['dead'],n),escaped=wilson(endpoints['escaped'],n),terminal_standing=wilson(endpoints['terminal_standing'],n)),
                initial_hp_strata=strata,resource_totals=dict(rations_remaining=sum(r['resources']['rations'] for r in rows),water_remaining=sum(r['resources']['water'] for r in rows)),
                seed_rows=compact(rows,COMBAT_COLUMNS),**row_digests(rows))

def resource_summary(scenario, rows):
    for row in rows:
        identity = scenario+':'+str(row['trial'])
        require(type(row['objective_completed']) is bool, identity+': objective type')
        require(type(row['initial_resources']) is dict and set(row['initial_resources']) == set(RESOURCES), identity+': initial resources shape')
        for field in RESOURCES:
            uint(row['initial_resources'][field], identity+'.initial_resources.'+field)
        for field in ('rests','refusals','fed_until','next_rest_at'):
            uint(row[field], identity+'.'+field)
        require(row['sequence'] == row['actions']-row['refusals'], identity+': sequence/refusals')
        require(len(row['refusal_codes']) == row['refusals'] and all(type(c) is str for c in row['refusal_codes']), identity+': refusal codes')
        require(row['active_seconds'] <= row['world_seconds'], identity+': active/world time')
        require(row['hp'] <= 8, identity+': resource fixture max HP')
        require(len(row['discoveries']) == len(set(row['discoveries'])), identity+': discovery duplicate')
        ids = [stock['id'] for stock in row['stocks']]
        require(len(ids) == len(set(ids)), identity+': stock duplicate')
        for stock in row['stocks']:
            for field in ('price','remaining','treasury'):
                uint(stock[field], identity+'.stock.'+field)
    stock_ids = [stock['id'] for stock in rows[0]['stocks']]
    stock_totals = []
    for row in rows:
        compare([stock['id'] for stock in row['stocks']], stock_ids, scenario+': stock identity/order')
    for stock_id in stock_ids:
        group = [next(s for s in row['stocks'] if s['id']==stock_id) for row in rows]
        stock_totals.append(dict(id=stock_id,remaining=sum(s['remaining'] for s in group),treasury=sum(s['treasury'] for s in group)))
    count, objectives = len(rows), sum(row['objective_completed'] for row in rows)
    return dict(scenario=scenario,count=count,objectives=objectives,
                **{field:sum(row[field] for row in rows) for field in ('standing','unconscious','dead')},
                totals=totals(rows,['refusals','rests','actions','world_seconds','active_seconds']),
                stock_totals=stock_totals,
                initial_resource_totals={field:sum(row['initial_resources'][field] for row in rows) for field in RESOURCES},
                resources_remaining={field:sum(row['resources'][field] for row in rows) for field in RESOURCES},
                seed_rows=compact(rows,RESOURCE_COLUMNS),objective_interval95=wilson(objectives,count),**row_digests(rows))

def decision_for(report, report_sha):
    return dict(protocol=PROTOCOL,training_report_sha256=report_sha,source_fingerprint=report['source']['fingerprint'],trials=report['result']['trials_per_cell'],recommendation=report['result']['recommendation'],selection_rule=report['result']['selection_rule'])

def verify_report(path, expected_trials, expected_source=None):
    report, report_sha = load(path)
    require(report['protocol']==PROTOCOL and report['phase'] in ('train','holdout'), 'Report protocol/phase')
    phase, result, source = report['phase'], report['result'], report['source']
    require(report['analysis_only'] is True, 'Not analysis-only report')
    require(report['preregistered_first_study'] == (expected_trials==500), 'First-study designation')
    require(type(source['files']) is dict and len(source['files']) > 0, 'Missing source files')
    for file, file_sha in source['files'].items():
        sha(file_sha, 'source.'+file)
    require(source['fingerprint'] == digest({'files':source['files'],'node':source['node']}), 'Source fingerprint mismatch')
    require(report['protocol_sha256'] == source['files']['scenarios/tempted-fates/balance/protocol.json'], 'Protocol hash differs from fingerprint file')
    require(type(source['commit']) is str and re.fullmatch('[0-9a-f]{40}',source['commit']), 'Source commit identity')
    if expected_source:
        require(source['commit'] == expected_source, 'Source differs from expected immutable SHA')
    require(result['trials_per_cell'] == expected_trials and expected_trials >= 500, 'Trial count differs from preregistration')
    require(len(result['combat'])==21 and len(result['resources'])==8, 'Arm/scenario counts differ')
    reconstructed, combat, resources = {}, [], []
    for summary, arm in zip(result['combat'], arms()):
        compare(summary['arm'], arm, 'arm')
        rows = reconstruct(summary,COMBAT_COLUMNS,'arm',arm['id'],expected_trials)
        reconstructed[arm['id']] = rows
        expected = combat_summary(arm,rows,phase)
        compare(summary,expected,arm['id'])
        combat.append(expected)
    for summary, scenario in zip(result['resources'], CASES):
        require(summary['scenario']==scenario, 'Resource scenario identity/order')
        rows = reconstruct(summary,RESOURCE_COLUMNS,'scenario',scenario,expected_trials)
        expected = resource_summary(scenario,rows)
        compare(summary,expected,scenario)
        resources.append(expected)
    comparisons = [comparison(hp,reconstructed[f'solo_{hp}_a11_fight'],reconstructed[f'solo_{hp}_a11_immediate']) for hp in ('classic','floor4')]
    censored = sum(c['endpoints']['censored'] for c in combat)
    recommendation = ('heldout-no-selection' if phase=='holdout' else 'inconclusive-censored' if censored else 'classic' if comparisons[0]['target']['status']=='match' else 'floor4' if comparisons[1]['target']['status']=='match' else 'no-target-match')
    expected_result = dict(protocol=PROTOCOL,phase=phase,trials_per_cell=expected_trials,study_eligible=True,
                           total_combat_trials=21*expected_trials,total_resource_trials=8*expected_trials,
                           combat=combat,comparisons=comparisons,resources=resources,recommendation=recommendation,
                           selection_rule=SELECTION_RULE,replay_digest=digest({'combat':[c['replay_digest'] for c in combat],'resources':[r['replay_digest'] for r in resources]}),analysis_note=ANALYSIS_NOTE)
    compare(result,expected_result,'result')
    return report, report_sha, {
        'report':str(Path(path).resolve()), 'report_sha256':report_sha, 'phase':phase,
        'source_commit':source['commit'], 'source_fingerprint':source['fingerprint'],
        'source_file_count':len(source['files']), 'trials_per_cell':expected_trials,
        'combat_rows_reconstructed':21*expected_trials, 'resource_rows_reconstructed':8*expected_trials,
        'censored_combat_rows':censored,'recommendation':recommendation,'comparisons':comparisons,
        'reconstructed_replay_digest':expected_result['replay_digest'],
        'integer_results_digests':{**{c['arm']['id']:c['integer_results_digest'] for c in combat}, **{r['scenario']:r['integer_results_digest'] for r in resources}},
        'checks':'All compact-row shape, basic outcome consistency, aggregate counts, denominators, HP strata, resource totals, retained-row digests, replay-summary digests, nominal Wilson/paired calculations and selection rules matched.'
    }

def self_test():
    compare(wilson(0,500)['low'],0)
    compare(wilson(500,500)['high'],1)
    require(wilson(0,500)['high'] > 0 and wilson(500,500)['low'] < 1, 'Boundary interval collapsed')
    require(paired([True]*500,[True]*500)['interval']['low'] < 0 < paired([True]*500,[True]*500)['interval']['high'], 'All-equal paired interval collapsed')
    require(paired([True]*500,[False]*500)['interval']['low'] < 1, 'All-improved paired interval collapsed')
    require(math.isclose(TARGET_Z,2.241402727604947,abs_tol=1e-14) and math.isclose(PAIRED_TARGET_Z,2.497705474412373,abs_tol=1e-14), 'Quantile mismatch')
    require(canonical_bytes({'b':[1,True,None],'a':'myth'}) == b'{"a":"myth","b":[1,true,null]}', 'Canonical JSON vector')
    try:
        json.loads('{"a":1,"a":2}',object_pairs_hook=duplicate_free)
    except ValueError:
        pass
    else:
        raise ValueError('Duplicate-key guard failed')
    caught = False
    try:
        compare({'value':1},{'value':2})
    except ValueError:
        caught = True
    require(caught, 'Mismatch guard failed')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report',nargs='?')
    parser.add_argument('--training')
    parser.add_argument('--decision')
    parser.add_argument('--expected-source')
    parser.add_argument('--expected-trials',type=int,default=500)
    parser.add_argument('--expected-sha')
    parser.add_argument('--output')
    parser.add_argument('--self-test',action='store_true')
    args = parser.parse_args()
    self_test()
    if args.self_test and not args.report:
        print(json.dumps({'status':'pass','self_test':True,'checks':CHECKS,'simulations_run':0}))
        return
    require(args.report is not None,'Report required')
    report, report_sha, audit = verify_report(args.report,args.expected_trials,args.expected_source)
    if args.expected_sha:
        require(report_sha == args.expected_sha,'Report differs from expected SHA-256')
    require(args.decision is not None,'Exact frozen decision input required')
    decision, decision_sha = load(args.decision)
    if report['phase']=='holdout':
        require(args.training is not None,'Training input required for heldout binding')
        training, training_sha, training_audit = verify_report(args.training,args.expected_trials)
        require(training['phase']=='train','Training input is not training')
        require(training['source']['fingerprint']==report['source']['fingerprint'],'Holdout source fingerprint changed')
        expected_decision = decision_for(training,training_sha)
        compare(report['frozen_decision'],expected_decision,'heldout.frozen_decision')
        audit['training_report_sha256'] = training_sha
        audit['frozen_training_recommendation'] = training['result']['recommendation']
        audit['training_reverified'] = True
    else:
        require(args.training is None,'Train verification must not receive other study')
        require(report['frozen_decision'] is None,'Training unexpectedly contains prior frozen decision')
        expected_decision = decision_for(report,report_sha)
    compare(decision,expected_decision,'decision')
    audit.update(status='pass',decision_sha256=decision_sha,decision_verified=True,
                 verifier_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                 checks=CHECKS,simulations_run=0,heldout_reports_read=1 if report['phase']=='holdout' else 0,
                 limits=[
                     'Report-only verification cannot recompute state or transition/replay transcript hashes; it checks retained row equality of transition and replay hashes plus every aggregate digest.',
                     'Source fingerprint self-consistency and optional expected immutable commit are checked; this script does not read repository source bytes.',
                     'No proof of absent unrecorded runs or seed peeking follows from report files alone.',
                     'Wilson score coverage is nominal, not an exact finite-sample family-wise guarantee; these fixed synthetic fixtures do not establish general player enjoyment or universal balance.'
                 ])
    text = json.dumps(audit,indent=2,sort_keys=True)+'\n'
    if args.output:
        Path(args.output).write_text(text)
    print(text,end='')

if __name__ == '__main__':
    main()
